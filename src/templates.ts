function shot(
  title: string,
  subtitle: string,
  seconds: number,
  motion: Scene['motion'],
  brand: string,
  heading: string,
  rows: string[],
  action: string,
): Omit<Scene, 'id' | 'asset'> {
  return { title, subtitle, seconds, motion, example: { brand, heading, rows, action } };
}

